"""tests/test_version.py — Sanity checks for version.py consistency."""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))

from version import __version__, __version_tuple__, APP_NAME


def test_version_is_valid_semver():
    assert re.fullmatch(r'\d+\.\d+\.\d+', __version__), \
        f"__version__ is not valid semver: {__version__!r}"


def test_version_tuple_matches_string():
    expected = tuple(int(x) for x in __version__.split('.'))
    assert __version_tuple__ == expected, \
        f"__version_tuple__ {__version_tuple__} != {expected} derived from the string"


def test_app_name_is_set():
    assert APP_NAME and isinstance(APP_NAME, str)


# ── The committed metadata must match the single source ───────────────────────

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
import version_sync   # noqa: E402


def test_derived_version_files_are_in_sync_with_version_py():
    """istari.iss and file_version_info.txt are generated by tools/version_sync.py.
    A stale committed copy puts a wrong version into the installer's file
    properties and the manual-build fallback."""
    assert version_sync.drift() == []
